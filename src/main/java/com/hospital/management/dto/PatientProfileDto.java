package com.hospital.management.dto;

public class PatientProfileDto {

    private Long id;
    private String name;
    private Integer age;
    private String gender;
    private String phone;
    private String bloodGroup;
    private String allergies;
    private String emergencyContact;
    private boolean isSelf = true;
    private String relationshipToAccount = "SELF";

    public PatientProfileDto() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public Integer getAge() {
        return age;
    }

    public void setAge(Integer age) {
        this.age = age;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getBloodGroup() {
        return bloodGroup;
    }

    public void setBloodGroup(String bloodGroup) {
        this.bloodGroup = bloodGroup;
    }

    public String getAllergies() {
        return allergies;
    }

    public void setAllergies(String allergies) {
        this.allergies = allergies;
    }

    public String getEmergencyContact() {
        return emergencyContact;
    }

    public void setEmergencyContact(String emergencyContact) {
        this.emergencyContact = emergencyContact;
    }

    public boolean isSelf() {
        return isSelf;
    }

    public void setSelf(boolean self) {
        isSelf = self;
    }

    public String getRelationshipToAccount() {
        return relationshipToAccount;
    }

    public void setRelationshipToAccount(String relationshipToAccount) {
        this.relationshipToAccount = relationshipToAccount;
    }
}
