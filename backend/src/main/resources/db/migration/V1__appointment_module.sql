UPDATE appointments
SET appointment_date = to_date(date, 'YYYY-MM-DD')
WHERE appointment_date IS NULL AND date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$';

UPDATE appointments
SET appointment_time = time::TIME
WHERE appointment_time IS NULL AND time ~ '^[0-9]{2}:[0-9]{2}(:[0-9]{2})?$';

UPDATE appointments
SET status = CASE LOWER(status)
    WHEN 'scheduled' THEN 'SCHEDULED'
    WHEN 'confirmed' THEN 'APPROVED'
    WHEN 'cancelled' THEN 'CANCELLED'
    WHEN 'completed' THEN 'COMPLETED'
    WHEN 'pending' THEN 'PENDING'
    WHEN 'approved' THEN 'APPROVED'
    WHEN 'rejected' THEN 'REJECTED'
    ELSE 'PENDING'
END;

