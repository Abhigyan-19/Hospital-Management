CREATE TABLE IF NOT EXISTS doctor_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL UNIQUE REFERENCES doctor(id),
    working_days VARCHAR(100) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    slot_minutes INTEGER NOT NULL,
    leave_dates TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS appointment_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES appointments(id),
    previous_status VARCHAR(20),
    new_status VARCHAR(20),
    previous_date DATE,
    previous_time TIME,
    new_date DATE,
    new_time TIME,
    changed_by_id BIGINT REFERENCES user_accounts(id),
    reason VARCHAR(1000),
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_appointment_history_appointment ON appointment_status_history(appointment_id, changed_at);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES user_accounts(id),
    appointment_id BIGINT REFERENCES appointments(id),
    notification_type VARCHAR(40) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    href VARCHAR(300) NOT NULL,
    deduplication_key VARCHAR(300) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_notifications_recipient_read_created
    ON notifications(recipient_id, read_at, created_at);
